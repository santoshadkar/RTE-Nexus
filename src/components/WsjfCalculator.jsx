import React, { useState } from 'react';
import { 
  Calculator, 
  ArrowUpDown, 
  Plus, 
  Trash2, 
  Copy, 
  Check, 
  HelpCircle, 
  Sparkles,
  TrendingUp,
  FileSpreadsheet
} from 'lucide-react';

export default function WsjfCalculator() {
  const [features, setFeatures] = useState([
    { id: 1, name: 'Real-Time Payment Gateway Integration', ubv: 8, tc: 13, rroe: 5, js: 5 },
    { id: 2, name: 'Automated Fraud Detection AI Microservice', ubv: 13, tc: 8, rroe: 8, js: 8 },
    { id: 3, name: 'Cloud Database Architecture Upgrade (Enabler)', ubv: 5, tc: 5, rroe: 13, js: 3 },
    { id: 4, name: 'Customer Mobile Dark Mode UI Theme', ubv: 3, tc: 2, rroe: 1, js: 2 },
    { id: 5, name: 'PCI-DSS Regulatory Compliance Security Patch', ubv: 8, tc: 20, rroe: 13, js: 3 }
  ]);

  const [newName, setNewName] = useState('');
  const [newUbv, setNewUbv] = useState(5);
  const [newTc, setNewTc] = useState(5);
  const [newRroe, setNewRroe] = useState(5);
  const [newJs, setNewJs] = useState(5);
  const [copied, setCopied] = useState(false);

  // Fibonacci scale options
  const fibOptions = [1, 2, 3, 5, 8, 13, 20];

  // Calculate WSJF for a feature
  const calculateWsjf = (f) => {
    const cod = f.ubv + f.tc + f.rroe;
    const wsjf = f.js > 0 ? cod / f.js : 0;
    return { cod, wsjf: Number(wsjf.toFixed(2)) };
  };

  // Sorted features by WSJF descending
  const sortedFeatures = [...features]
    .map(f => ({ ...f, ...calculateWsjf(f) }))
    .sort((a, b) => b.wsjf - a.wsjf);

  const handleAddFeature = (e) => {
    e.preventDefault();
    if (!newName.trim()) return;
    setFeatures([
      ...features,
      {
        id: Date.now(),
        name: newName,
        ubv: Number(newUbv),
        tc: Number(newTc),
        rroe: Number(newRroe),
        js: Number(newJs)
      }
    ]);
    setNewName('');
    setNewUbv(5);
    setNewTc(5);
    setNewRroe(5);
    setNewJs(5);
  };

  const handleDelete = (id) => {
    setFeatures(features.filter(f => f.id !== id));
  };

  const handleExportMarkdown = () => {
    const tableHeader = `# WSJF PRIORITIZED BACKLOG TABLE\nGenerated on: ${new Date().toLocaleDateString()}\n\n| Rank | Feature / Capability Name | User-Business Value (UBV) | Time Criticality (TC) | Risk Red / Opp Enabler (RR/OE) | Cost of Delay (CoD) | Job Size (JS) | WSJF Score |\n|---|---|---|---|---|---|---|---|`;
    const tableRows = sortedFeatures.map((f, idx) => 
      `| **#${idx + 1}** | ${f.name} | ${f.ubv} | ${f.tc} | ${f.rroe} | **${f.cod}** | ${f.js} | **${f.wsjf}** |`
    ).join('\n');
    
    const output = `${tableHeader}\n${tableRows}\n\n*Prioritization rule: Higher WSJF items enter PI Planning first for maximum economic return.*`;
    navigator.clipboard.writeText(output);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  return (
    <div className="space-y-8 animate-fadeIn">
      
      {/* Header Banner */}
      <div className="glass-panel p-8 rounded-3xl border border-sky-500/30 bg-gradient-to-r from-navy-950 via-navy-900 to-indigo-950 space-y-3">
        <div className="inline-flex items-center space-x-2 px-3 py-1 rounded-full bg-sky-500/10 border border-sky-500/30 text-sky-300 text-xs font-semibold">
          <Calculator className="w-3.5 h-3.5 text-sky-400" />
          <span>SAFe Economic Prioritization Model</span>
        </div>
        <h1 className="text-3xl sm:text-5xl font-heading font-extrabold text-white tracking-tight">
          Interactive <span className="text-gradient">WSJF Priority Calculator</span>
        </h1>
        <p className="text-slate-300 text-xs sm:text-sm leading-relaxed max-w-4xl">
          Weighted Shortest Job First (WSJF) is the mathematical prioritization framework used by RTEs and Product Management to sequence features by economic value: <strong>WSJF = Cost of Delay (UBV + TC + RR/OE) / Job Size</strong>.
        </p>
      </div>

      {/* Formula Explainer Cards */}
      <div className="grid grid-cols-1 md:grid-cols-4 gap-4">
        <div className="p-4 rounded-2xl bg-navy-900 border border-slate-800 space-y-1">
          <span className="text-[10px] font-bold text-sky-400 uppercase tracking-wider block">Component 1</span>
          <h3 className="text-sm font-bold text-white">User-Business Value (UBV)</h3>
          <p className="text-[11px] text-slate-300">Direct revenue, customer retention, or brand value generated by the feature.</p>
        </div>

        <div className="p-4 rounded-2xl bg-navy-900 border border-slate-800 space-y-1">
          <span className="text-[10px] font-bold text-emerald-400 uppercase tracking-wider block">Component 2</span>
          <h3 className="text-sm font-bold text-white">Time Criticality (TC)</h3>
          <p className="text-[11px] text-slate-300">Urgency of delivery: Is there a fixed market window, contractual SLA, or regulatory deadline?</p>
        </div>

        <div className="p-4 rounded-2xl bg-navy-900 border border-slate-800 space-y-1">
          <span className="text-[10px] font-bold text-amber-400 uppercase tracking-wider block">Component 3</span>
          <h3 className="text-sm font-bold text-white">Risk Red / Opp Enabler (RR/OE)</h3>
          <p className="text-[11px] text-slate-300">Does it eliminate future outage risks, solve security debt, or unlock follow-on business?</p>
        </div>

        <div className="p-4 rounded-2xl bg-navy-900 border border-slate-800 space-y-1">
          <span className="text-[10px] font-bold text-rose-400 uppercase tracking-wider block">Divisor</span>
          <h3 className="text-sm font-bold text-white">Job Size / Duration (JS)</h3>
          <p className="text-[11px] text-slate-300">Relative development effort and duration estimated across team capacity (Fibonacci).</p>
        </div>
      </div>

      {/* Add Feature Form */}
      <div className="glass-panel p-6 sm:p-8 rounded-3xl border border-slate-800 space-y-4">
        <div className="flex items-center justify-between border-b border-slate-800 pb-3">
          <h2 className="text-base font-bold text-white flex items-center space-x-2">
            <Plus className="w-4 h-4 text-sky-400" />
            <span>Add Feature / Capability to Prioritization Board</span>
          </h2>
          <span className="text-xs text-slate-400">Scale: Fibonacci (1, 2, 3, 5, 8, 13, 20)</span>
        </div>

        <form onSubmit={handleAddFeature} className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-6 gap-3">
          <div className="lg:col-span-2">
            <label className="text-[11px] font-bold text-slate-300 block mb-1">Feature Name</label>
            <input
              type="text"
              placeholder="e.g. Real-Time Telemetry Streaming"
              value={newName}
              onChange={(e) => setNewName(e.target.value)}
              className="w-full bg-navy-950 border border-slate-800 rounded-xl p-2.5 text-xs text-white focus:border-sky-400 focus:outline-none"
            />
          </div>

          <div>
            <label className="text-[11px] font-bold text-slate-300 block mb-1">User Value (UBV)</label>
            <select
              value={newUbv}
              onChange={(e) => setNewUbv(e.target.value)}
              className="w-full bg-navy-950 border border-slate-800 rounded-xl p-2.5 text-xs text-white font-bold"
            >
              {fibOptions.map(n => <option key={n} value={n}>{n}</option>)}
            </select>
          </div>

          <div>
            <label className="text-[11px] font-bold text-slate-300 block mb-1">Time Criticality (TC)</label>
            <select
              value={newTc}
              onChange={(e) => setNewTc(e.target.value)}
              className="w-full bg-navy-950 border border-slate-800 rounded-xl p-2.5 text-xs text-white font-bold"
            >
              {fibOptions.map(n => <option key={n} value={n}>{n}</option>)}
            </select>
          </div>

          <div>
            <label className="text-[11px] font-bold text-slate-300 block mb-1">Risk / Opp (RR/OE)</label>
            <select
              value={newRroe}
              onChange={(e) => setNewRroe(e.target.value)}
              className="w-full bg-navy-950 border border-slate-800 rounded-xl p-2.5 text-xs text-white font-bold"
            >
              {fibOptions.map(n => <option key={n} value={n}>{n}</option>)}
            </select>
          </div>

          <div>
            <label className="text-[11px] font-bold text-slate-300 block mb-1">Job Size (JS)</label>
            <div className="flex space-x-2">
              <select
                value={newJs}
                onChange={(e) => setNewJs(e.target.value)}
                className="flex-1 bg-navy-950 border border-slate-800 rounded-xl p-2.5 text-xs text-white font-bold"
              >
                {fibOptions.map(n => <option key={n} value={n}>{n}</option>)}
              </select>
              <button
                type="submit"
                className="px-4 py-2.5 rounded-xl bg-emerald-600 hover:bg-emerald-500 text-white font-bold text-xs"
              >
                Add
              </button>
            </div>
          </div>
        </form>
      </div>

      {/* Sorted WSJF Results Table */}
      <div className="glass-panel p-6 sm:p-8 rounded-3xl border border-slate-800 space-y-4">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-slate-800 pb-4">
          <div>
            <h2 className="text-xl font-heading font-bold text-white flex items-center space-x-2">
              <ArrowUpDown className="w-5 h-5 text-sky-400" />
              <span>Prioritized Delivery Horizon (Ranked by WSJF)</span>
            </h2>
            <p className="text-xs text-slate-400">Items at the top deliver the highest economic return per unit of capacity.</p>
          </div>

          <button
            onClick={handleExportMarkdown}
            className="px-4 py-2 rounded-xl bg-sky-600 hover:bg-sky-500 text-white text-xs font-bold flex items-center space-x-2 shadow-glow-sapphire"
          >
            {copied ? <Check className="w-4 h-4 text-emerald-300" /> : <Copy className="w-4 h-4" />}
            <span>{copied ? 'Markdown Copied!' : 'Export WSJF Table'}</span>
          </button>
        </div>

        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs border-collapse">
            <thead>
              <tr className="border-b border-slate-800 bg-navy-950 text-slate-300 uppercase tracking-wider">
                <th className="p-3.5 rounded-tl-xl font-bold">Rank</th>
                <th className="p-3.5 font-bold">Feature Name</th>
                <th className="p-3.5 font-bold text-center">UBV</th>
                <th className="p-3.5 font-bold text-center">TC</th>
                <th className="p-3.5 font-bold text-center">RR/OE</th>
                <th className="p-3.5 font-bold text-center bg-sky-950/40 text-sky-300">Cost of Delay</th>
                <th className="p-3.5 font-bold text-center">Job Size</th>
                <th className="p-3.5 font-bold text-center bg-emerald-950/40 text-emerald-300">WSJF Score</th>
                <th className="p-3.5 rounded-tr-xl font-bold text-center">Action</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-800/60 text-slate-200">
              {sortedFeatures.map((f, idx) => (
                <tr key={f.id} className="hover:bg-navy-900/60 transition-colors">
                  <td className="p-3.5 font-bold">
                    <span className={`px-2.5 py-1 rounded-full text-xs font-extrabold ${
                      idx === 0 ? 'bg-amber-500/20 text-amber-300 border border-amber-500/30' :
                      idx === 1 ? 'bg-sky-500/20 text-sky-300 border border-sky-500/30' :
                      idx === 2 ? 'bg-indigo-500/20 text-indigo-300 border border-indigo-500/30' :
                      'bg-slate-800 text-slate-400'
                    }`}>
                      #{idx + 1}
                    </span>
                  </td>
                  <td className="p-3.5 font-medium text-white">{f.name}</td>
                  <td className="p-3.5 text-center font-mono">{f.ubv}</td>
                  <td className="p-3.5 text-center font-mono">{f.tc}</td>
                  <td className="p-3.5 text-center font-mono">{f.rroe}</td>
                  <td className="p-3.5 text-center font-mono font-bold text-sky-300 bg-sky-950/20">{f.cod}</td>
                  <td className="p-3.5 text-center font-mono">{f.js}</td>
                  <td className="p-3.5 text-center font-mono font-extrabold text-emerald-400 bg-emerald-950/20 text-sm">{f.wsjf}</td>
                  <td className="p-3.5 text-center">
                    <button
                      onClick={() => handleDelete(f.id)}
                      className="p-1.5 text-slate-500 hover:text-rose-400 transition-colors"
                    >
                      <Trash2 className="w-4 h-4" />
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>

    </div>
  );
}
